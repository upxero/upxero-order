const MAPS = { en: EN };

export function makeT(lang) {
  const code = lang === "nl" ? "nl" : "en";
  const map = MAPS[code];
  return (s, vars) => {
    let out = code === "nl" || !map ? s : (map[s] ?? s);
    if (vars) for (const k of Object.keys(vars)) out = out.replaceAll(`{${k}}`, vars[k]);
    return out;
  };
}

